/**
 * BUILDS `lib/blog/posts.generated.ts` FROM `content/blog/*.md` (blog section, 24 Nov 2026).
 *
 *   node scripts/blog/build-blog.mjs        (npm run blog:build)
 *
 * WHY THE POSTS ARE EMBEDDED AND NOT READ FROM DISK. A file read at request time has to be traced into every
 * serverless function that reads it (`outputFileTracingIncludes`), and the footer of every page asks whether
 * there is a post to link to. One missed route would be a page that works locally and fails deployed — the
 * failure `/terms` had with `content/legal`. Embedded text is in the bundle wherever it is imported.
 *
 * THE MARKDOWN FILES ARE THE SOURCE. Edit, add or delete a post there and run this;
 * `lib/blog/__tests__/generated.test.ts` fails when the two disagree, so a forgotten rebuild is caught before it
 * is merged.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const sourceDirectory = path.join(root, "content", "blog");
const EXTENSION = ".md";

const slugs = readdirSync(sourceDirectory)
  .filter((file) => file.endsWith(EXTENSION))
  .sort()
  .map((file) => file.slice(0, -EXTENSION.length));

const entries = slugs.map((slug) => {
  const source = readFileSync(path.join(sourceDirectory, `${slug}${EXTENSION}`), "utf8");
  return `  ${JSON.stringify(slug)}: ${JSON.stringify(source)},`;
});

const generated = [
  "// GENERATED by scripts/blog/build-blog.mjs from content/blog/*.md.",
  "// Do not edit: change the Markdown file and run `npm run blog:build`.",
  "",
  "export const BLOG_SOURCES: Readonly<Record<string, string>> = {",
  ...entries,
  "};",
  "",
].join("\n");

writeFileSync(path.join(root, "lib", "blog", "posts.generated.ts"), generated);
process.stdout.write(`wrote lib/blog/posts.generated.ts (${entries.length} posts)\n`);
