/**
 * Dev helper: builds a translation overlay (e.g. lib/i18n/th.ts) from flat `key -> translation` JSON files, using the
 * English table for structure. Arrays are written whole (the resolver replaces arrays wholesale), filling any item
 * field that has no translation with the English value. Run with vite-node:
 *   vite-node --config vitest.config.ts scripts/i18n-build.ts <export-name> <out.ts> <in1.json> [in2.json …]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { strings } from "@/lib/strings";

const [name, outPath, ...inputs] = process.argv.slice(2);
const flat: Record<string, string> = Object.assign({}, ...inputs.map((p) => JSON.parse(readFileSync(p, "utf8"))));

function build(english: unknown, prefix: string): unknown {
  if (typeof english === "string") return flat[prefix];
  if (Array.isArray(english)) {
    const items = english.map((item, i) => buildFull(item, `${prefix}[${i}]`));
    const touched = english.some((item, i) => JSON.stringify(item) !== JSON.stringify(items[i]));
    return touched ? items : undefined;
  }
  if (english && typeof english === "object") {
    const out: Record<string, unknown> = {};
    for (const [k, v] of Object.entries(english)) {
      const child = build(v, prefix ? `${prefix}.${k}` : k);
      if (child !== undefined) out[k] = child;
    }
    return Object.keys(out).length ? out : undefined;
  }
  return undefined;
}
/** Inside an array every field is written, translated or English. */
function buildFull(english: unknown, prefix: string): unknown {
  if (typeof english === "string") return flat[prefix] ?? english;
  if (Array.isArray(english)) return english.map((item, i) => buildFull(item, `${prefix}[${i}]`));
  if (english && typeof english === "object")
    return Object.fromEntries(Object.entries(english).map(([k, v]) => [k, buildFull(v, `${prefix}.${k}`)]));
  return english;
}

const overlay = build(strings, "") as Record<string, unknown>;
const used = new Set<string>();
(function mark(v: unknown, p: string) {
  if (typeof v === "string") used.add(p);
  else if (Array.isArray(v)) v.forEach((x, i) => mark(x, `${p}[${i}]`));
  else if (v && typeof v === "object") for (const [k, c] of Object.entries(v)) mark(c, p ? `${p}.${k}` : k);
})(strings, "");
const unknown = Object.keys(flat).filter((k) => !used.has(k));
if (unknown.length) throw new Error(`keys not in the English table: ${unknown.join(", ")}`);

const header = `import type { StringsOverlay } from "@/lib/i18n/resolve";

/**
 * THAI — the player-facing overlay (Playco rebrand). MACHINE TRANSLATION, NOT YET REVIEWED BY A NATIVE SPEAKER.
 *
 * Generated by scripts/i18n-build.ts from reviewed JSON; edit the strings here directly once a Thai speaker has been
 * through them. Missing keys fall back to English (lib/i18n/resolve.ts). Placeholders in braces and **bold** markers
 * must survive any edit.
 */
`;
writeFileSync(outPath, `${header}export const ${name}: StringsOverlay = ${JSON.stringify(overlay, null, 2)};\n`);
process.stdout.write(`wrote ${outPath}: ${Object.keys(flat).length} strings\n`);
